# удобная компоновка строк из переменных
a = 1
b = 2

# классическое выражение (неудобное)
print("a = " + str(a) + ", b = " + str(b) + ", a+b = " + str(a+b))  # выдаст "a = 1, b = 2, a+b = 3"

# короткое выражение через f-строку (удобное)
# в f-строках можно вставлять значения переменных прямо в середину строки
print(f"a = {a}, b = {b}, a+b = {a+b}")  # выдаст "a = 1, b = 2, a+b = 3"

# объединение последовательностей
print("join методы")

# изначальный список
initial_list = ['str1', 'str2', 'str3']
# объединение элементов списка в строку, разделяя их запятой с пробелом
print(', '.join(initial_list))  # выдаст "str1, str2, str3"

# изначальный кортеж
initial_tuple= ('str1', 'str2', 'str3')
# объединение элементов списка в строку, разделяя их запятой с пробелом
print(', '.join(initial_tuple))  # выдаст "str1, str2, str3"

# разделение символов строк
initial_str = 'qwer'
# разделители между символами строки
print(' '.join(initial_str))  # выдаст "q w e r"
