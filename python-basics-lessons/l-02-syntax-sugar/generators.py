# получение квадратов чисел из изначальной последовательности
squares = [x ** 2 for x in range(5)]
print(squares)  # выдаст квадраты четных чисел [0, 1, 4, 9, 16]

# получение квадратов чисел из только четных чисел изначальной последовательности
even_squares = [x ** 2 for x in range(5) if x % 2 == 0]
print(even_squares)  # выдаст квадраты четных чисел [0, 4, 16]

# словарь, где ключ - элемент из изначальной последовательности,
# а значение - квадрат соответствующего числа
squares_dict = {x: x ** 2 for x in range(5)}
print(squares_dict)  # выдаст {0: 0, 1: 1, 2: 4, 3: 9, 4: 16}

# получение квадратов чисел из изначальной последовательности и создание генератора кортежей из них
squares_tuple = (x ** 2 for x in range(5))
print(tuple(squares_tuple))  # выдаст (0, 1, 4, 9, 16)
