# изначальный список
initial_list = [0, 1, 2, 3, 4, 5, 6, 7]

# обрезание листа с концов
print('обрезание листа с концов')
# вырежем кусок списка с начала вплоть до пятого элемента (не включительно)
print(initial_list[:5])  # выдаст [0, 1, 2, 3, 4]
# вырежем кусок списка со второго элемента (включительно) до пятого элемента (не включительно)
print(initial_list[2:5])  # выдаст [2, 3, 4]
# вырежем кусок списка со второго элемента (включительно) до конца
print(initial_list[2:])  # выдаст [2, 3, 4, 5, 6, 7]

# индексы элементов также можно указывать с конца
print('обрезание листа с концов (указание индексов с конца)')
# вырежем кусок списка с предпоследнего элемента (включительно) до конца
print(initial_list[-2:])  # выдаст [6, 7]
# вырежем кусок списка с третьего с конца элемента (включительно) до последнего (не включительно)
print(initial_list[-3:-1])  # выдаст [5, 6]

# также можно выбирать шаг, с которым будем проходиться по элементам
print('обрезание листа с выбором шага')
# каждый третий элемент
print(initial_list[::3])  # выдаст [0, 3, 6]
# каждый третий элемент, начиная со второго
print(initial_list[2::3])  # выдаст [2, 5]
# каждый третий элемент, вплоть до предпоследнего (не включительно)
print(initial_list[:-2:3])  # выдаст [0, 3]

# слайсы можно делать не только с листами
print('слайсы на строках и кортежах')

# подобные операции можно делать также со строками
initial_string = '1234567'
# вырежем кусок строки со второго элемента (включительно) до предпоследнего (не включительно)
print(initial_string[2:-2])  # выдаст '345'

# слайсы можно делать и на кортежах
initial_tuple = (0, 1, 2, 3)
# вырежем кусок строки с первого элемента (включительно) до последнего (не включительно)
print(initial_tuple[1:-1])  # выдаст (1, 2)

