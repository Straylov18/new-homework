a = 42
b = input('ну-ка введи что-нить сюда: ')

try:
    # тут пишем код, в котором потенциально могла бы быть ошибка
    print(a / int(b))
    if b == '69':
        raise Exception('сами вывели ошибку')
except ZeroDivisionError:
    # тут пишем что нужно делать, если произошло деление на ноль
    print('Нельзя делить на ноль ..')
except ValueError:
    # тут пишем что нужно делать, если невозможно произвести операцию с введенным типом данных
    print('Надо было вводить число)')
except Exception:
    # тут пишем что нужно делать, если произошла любая другая ошибка (в самом крайнем случае пишем)
    print('Что-то пошло не так! Хто я? Де я?')
finally:
    # этот код исполнится, вне зависимости от того, выкинулось ли какое-либо исключение или же все отработало штатно
    # обычно нужно, чтобы закрыть доступы к ресурсам (при чтении файла там)
    print('Так или иначе выполняется после всего этого (вне зависимости от того, есть ошибка или нет)')

print('---------- получение информации об исключении в блоке except ----------')

c = input('еще разок: ')

try:
    print(a / int(c))
except Exception as e:
    print(e)

print('---------- свои классы исключений ----------')


class Exception69(Exception):
    pass


d = input('не вводи 69: ')

try:
    if d == '69':
        raise Exception69('Текст ошибки')
except Exception69 as e69:
    print('успешно перехватили ввод 69')
    print(e69)

