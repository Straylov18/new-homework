a = 42
b = input('ну-ка введи что-нить сюда: ')

try:
    # тут пишем код, в котором потенциально могла бы быть ошибка
    print(a / int(b))
    if b == '69':
        raise Exception('сами вывели ошибку')
except ZeroDivisionError:
    # тут пишем что нужно делать, если произошло деление на ноль
    print('Нельзя делить на ноль ..')
except ValueError:
    # тут пишем что нужно делать, если невозможно произвести операцию с введенным типом данных
    print('Надо было вводить число)')
except Exception:
    # тут пишем что нужно делать, если произошла любая другая ошибка (в самом крайнем случае пишем)
    print('Что-то пошло не так! Хто я? Де я?')
finally:
    # этот код исполнится всегда в самом конце выражения
    # вне зависимости от того, выкинулось ли какое-либо исключение или же все отработало штатно
    # обычно используется, чтобы закрыть доступы к ресурсам (при чтении файла там)
    print('Так или иначе выполняется после всего этого (вне зависимости от того, есть ошибка или нет)')

print('---------- получение информации об исключении в блоке except ----------')

c = input('еще разок: ')

try:
    print(a / int(c))
except Exception as e:
    print(e)

print('---------- свои классы исключений ----------')


class Exception69(Exception):
    pass


d = input('не вводи 69: ')

try:
    if d == '69':
        raise Exception69('Текст ошибки')
except Exception69 as e69:
    print('успешно перехватили ввод 69')
    print(e69)  # выведет 'Текст ошибки'

print('---------- работа с файлами ----------')

# работа с фалами через try finally
f = open('text.txt', 'w')
# w - запись текста
# a - запись текста в конец файла
# r - чтение текста
# wb - бинарная запись
# ab - бинарная запись в конец файла
# rb - чтение запись
# итд.
try:
    f.write('текст, запихнутый в файл ...\n')
finally:
    f.close()

print('---------- контекстные менеджеры ----------')

# если использовать контекстный менеджер через with, то f.close() будет всегда выполняться автоматически
f = open('text.txt', 'a')
with f:
    f.write('текст, запихнутый в файл 1 ...\n')

# для упрощения можно задавать контекстный менеджер прям тут используя 'as'
with open('text.txt', 'a') as f:
    f.write('текст, запихнутый в файл 2 ...\n')

print('---------- собственные контекстные менеджеры ----------')


class MyVeryOwnContextManager:
    def __enter__(self):
        print('отработает в строчке с "with"')
        # в переменную после 'as' передастся то, что здесь будет в return (принято выдавать self)
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        print('ошибочка: ', exc_val)
        print('отработал exit')
        if exc_type == Exception69:
            # поскольку в случае Exception69 будет возвращаться True, при ее возникновении она вообще не будет вылезать
            return True

    def some_operations(self):
        print('что-то делается ..')


with MyVeryOwnContextManager() as mcm:
    mcm.some_operations()

with MyVeryOwnContextManager() as mcm:
    mcm.some_operations()
    # ошибка не вылезет, потому что в __exit__ при Exception69 возвращается True
    raise Exception69('Пупупу')

with MyVeryOwnContextManager() as mcm:
    mcm.some_operations()
    # !!!  ошибка вылезет !!!
    raise Exception('Ошибка, которая таки вылезет')
